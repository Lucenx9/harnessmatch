import {
  parseGitHubReleaseDownloads,
  parseGitHubRepository,
  parseHomebrewAnalytics,
} from "./ecosystem-signals.mjs";

function normalizedUrl(value) {
  return String(value ?? "").replace(/\/$/, "").toLowerCase();
}

export function validateGuiHomebrewIdentity(payload, artifact) {
  if (payload?.token !== artifact.artifactId) {
    throw new Error(`Homebrew GUI identity changed for ${artifact.artifactId}`);
  }
  if (!Array.isArray(payload.name) || !payload.name.includes(artifact.name)) {
    throw new Error(`Homebrew GUI name changed for ${artifact.artifactId}`);
  }
  if (normalizedUrl(payload.homepage) !== normalizedUrl(artifact.homepage)) {
    throw new Error(`Homebrew GUI homepage changed for ${artifact.artifactId}`);
  }
  if (typeof payload.version !== "string" || payload.version.length === 0) {
    throw new Error(`Homebrew GUI version is missing for ${artifact.artifactId}`);
  }
}

export function parseGuiHomebrewAnalytics(payload, artifacts, identities, observedAt) {
  const identityByArtifact = new Map(identities.map((identity) => [identity.token, identity]));
  const harnessShapedArtifacts = artifacts.map(({ guiId, ...artifact }) => ({
    ...artifact,
    harnessId: guiId,
    artifactKind: "cask",
  }));
  const parsed = parseHomebrewAnalytics(payload, harnessShapedArtifacts, "cask", observedAt);

  return parsed.map(({ harnessId, artifactKind: _artifactKind, ...signal }) => {
    const artifact = artifacts.find((candidate) => candidate.guiId === harnessId);
    const identity = artifact ? identityByArtifact.get(artifact.artifactId) : undefined;
    if (!artifact || !identity) throw new Error(`Homebrew GUI identity payload is missing for ${harnessId}`);
    validateGuiHomebrewIdentity(identity, artifact);
    return {
      ...signal,
      guiId: harnessId,
      latestVersion: identity.version,
    };
  });
}

export function parseGuiGitHubRepository(payload, audit, observedAt) {
  const parsed = parseGitHubRepository(payload, {
    harnessId: audit.guiId,
    repositoryUrl: audit.repositoryUrl,
    sourceScope: audit.sourceScope,
  }, observedAt);
  const { harnessId, ...signal } = parsed;
  return { ...signal, guiId: harnessId };
}

export function parseGuiGitHubReleaseDownloads(releases, artifact, audit, observedAt) {
  const parsed = parseGitHubReleaseDownloads(releases, {
    harnessId: artifact.guiId,
    includePatterns: artifact.includePatterns,
    includeTagPatterns: artifact.includeTagPatterns,
    includeNamePatterns: artifact.includeNamePatterns,
    artifactScope: artifact.artifactScope,
  }, {
    harnessId: audit.guiId,
    repositoryUrl: audit.repositoryUrl,
    sourceScope: audit.sourceScope,
  }, observedAt);
  const { harnessId, ...signal } = parsed;
  return { ...signal, guiId: harnessId };
}

export function parseGuiRepositoryAuditSource(source) {
  const guiId = source.match(/guiId:\s*"([^"]+)"/)?.[1];
  const repositoryUrl = source.match(/repositoryUrl:\s*"(https:\/\/github\.com\/[^"]+)"/)?.[1];
  const sourceScope = source.match(/sourceScope:\s*"(full-source|client-source)"/)?.[1];
  if (!guiId || !repositoryUrl || !sourceScope) return null;
  return { guiId, repositoryUrl, sourceScope };
}

function formatInteger(value) {
  return value.toLocaleString("en-US").replaceAll(",", "_");
}

function renderValue(value) {
  if (typeof value === "number") return formatInteger(value);
  return JSON.stringify(value);
}

export function renderGuiEcosystemSignalsFile(signals) {
  const records = signals.map((signal) => {
    const orderedKeys = [
      "source", "metric", "guiId", "artifactId", "value", "forks", "repositoryScope",
      "latestVersion", "assetCount", "releaseCount", "recentReleaseCount", "recentReleaseWindowDays",
      "latestReleaseAt", "latestReleaseUrl", "artifactScope", "windowDays", "windowStart", "windowEnd",
      "observedAt", "artifactUrl", "sourceUrl",
    ];
    const lines = ["  {"];
    for (const key of orderedKeys) {
      if (signal[key] === undefined) continue;
      lines.push(`    ${key}: ${renderValue(signal[key])},`);
    }
    lines.push("  },");
    return lines.join("\n");
  }).join("\n");

  return `import type { GuiEcosystemSignalSnapshot } from "../lib/gui-types";\n\n/**\n * Generated by \`npm run sync:gui-signals\` from Homebrew and GitHub APIs.\n * Source-native units stay separate and never enter GUI workflow-fit results.\n */\nexport const guiEcosystemSignalSnapshots: GuiEcosystemSignalSnapshot[] = [\n${records}\n];\n\nexport const guiEcosystemSignalsByProduct = new Map<string, GuiEcosystemSignalSnapshot[]>();\nfor (const signal of guiEcosystemSignalSnapshots) {\n  const existing = guiEcosystemSignalsByProduct.get(signal.guiId) ?? [];\n  existing.push(signal);\n  guiEcosystemSignalsByProduct.set(signal.guiId, existing);\n}\n`;
}
